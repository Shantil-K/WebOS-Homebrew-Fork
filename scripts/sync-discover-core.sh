#!/bin/sh
# Copies the shared Discoverium core from the TV app so the phone and the TV judge versions the same way.
# Usage: scripts/sync-discover-core.sh [path/to/DiscoveriumTV]
SRC="${1:-../DiscoveriumTV}/src/core/discover-core.js"
OUT="src/app/discover/discover-core.ts"
{
  echo "// @ts-nocheck"
  echo "// Generated by scripts/sync-discover-core.sh from DiscoveriumTV/src/core/discover-core.js. Do not edit here."
  sed -e 's/})(typeof window !== "undefined" ? window : this);/})(globalThis);/' \
      -e 's/^\tif (typeof module !== "undefined" \&\& module.exports) module.exports = API;$//' \
      -e 's/^\telse root.DiscoverCore = API;$/\troot.DiscoverCore = API;/' "$SRC"
  echo 'export const DiscoverCore = globalThis.DiscoverCore;'
} > "$OUT"
echo "wrote $OUT"
